"""案件管理DBの「提案サービス」（案件側の表記）とテンプレート管理DB「【営業部】見積書／規約／
申込書／契約書」の「サービス」（テンプレート側の表記）を対応付けるマッピング。

案件側は同一サービスでもプラン違い等により複数の表記ゆれがある（例:「ホテルラボ St＋」
「ホテルラボ Ri」等はいずれもテンプレート側では単一の「ホテルラボ」に対応する）ため、
多対1のマッピングとして辞書リテラルで明示的に定義する（`src/db_schema/project.py`の
「提案サービス」optionsとテンプレート管理DBの「サービス」multi_select値の実データに基づく）。
"""

from __future__ import annotations

# 案件側「提案サービス」→テンプレート側「サービス」。マッピングに無いキー（「その他」
# 「ビールオーダー」「パーソネル」「WEB制作（楽天CP・自社HP）」）はテンプレート未対応として扱う
# （generate_*関数はTemplateNotFoundErrorを送出し、APIは422を返す）。
PROJECT_TO_TEMPLATE_SERVICE: dict[str, str] = {
    "リピッテ": "リピッテホテル",
    "メイリー": "メイリー",
    "ホテルラボ St＋": "ホテルラボ",
    "ホテルラボ St": "ホテルラボ",
    "ホテルラボ Ri＋": "ホテルラボ",
    "ホテルラボ Ri": "ホテルラボ",
    "ホテルラボ In": "ホテルラボ",
    "ホテルラボ WEBサポート": "ホテルラボ",
    "ホテルラボ レビュー（口コミ返信代行）": "口コミ返信",
    "Growth Cube（オルト（alt））": "オルト",
    "ノバシテ": "SNS運用",
    "ILCA（三密代官、HOTEL DX）": "ILCA",
    "LevGo（クリエイティブラボ）": "LevGo",
    "デザ丸": "デザ丸",
    "レベニューマネジメント": "ホテルラボRM",
    "レセプション": "レセプション",
    "フルスコ": "フルスコ",
}


def resolve_template_service(project_service: str) -> str | None:
    """案件側の「提案サービス」表記を、テンプレート管理DBの「サービス」表記へ変換する。

    マッピングに存在しない値はテンプレート未対応としてNoneを返す。
    """
    return PROJECT_TO_TEMPLATE_SERVICE.get(project_service)
